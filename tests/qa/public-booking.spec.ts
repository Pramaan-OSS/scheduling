import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
const fixture = JSON.parse(readFileSync(".scratch/qa/fixtures.json", "utf8"));
test.use({ storageState: { cookies: [], origins: [] } });
test.beforeEach(async ({ context }) => { await context.route("**/*", route => ["localhost", "127.0.0.1"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort()); });
test("guest creates a booking and can review its reschedule and cancellation actions", async ({ page }) => {
  await page.goto(`/${fixture.username}/qa-public`);
  await page.getByRole("button", { name: /^\d{1,2}:\d{2}(am|pm)$/ }).first().click();
  await page.locator('input[name="name"]').fill("QA lifecycle guest");
  await page.locator('input[name="email"]').fill("lifecycle-guest@example.test");
  await expect(page.locator('a[href="/terms"], a[href="/privacy"]')).toHaveCount(0);
  await page.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(page).toHaveURL(/\/booking\//, { timeout: 120000 });
  await expect(page.getByText(/This meeting is scheduled|Booking confirmed|You are scheduled/i).first()).toBeVisible();
  await expect(page.locator("body")).not.toContainText("We sent an email with a calendar invitation");
  let path = new URL(page.url()).pathname;
  await page.screenshot({ path: ".scratch/qa/public-confirmed.png", fullPage: true });
  const reschedule = page.getByRole("button", { name: /reschedule/i }).or(page.getByRole("link", { name: /reschedule/i }));
  await expect(reschedule.first()).toBeVisible();
  await reschedule.first().click();
  await expect(page).toHaveURL(/rescheduleUid=/);
  await expect(page.getByRole("button", { name: /^\d{1,2}:\d{2}(am|pm)$/ }).first()).toBeVisible();
  await page.getByRole("button", { name: /^\d{1,2}:\d{2}(am|pm)$/ }).nth(1).click();
  const changed = page.waitForResponse(response => new URL(response.url()).pathname === "/api/book/event" && response.request().method() === "POST");
  await page.getByTestId("confirm-reschedule-button").filter({ visible: true }).click();
  const change = await changed; expect(change.ok()).toBe(true);
  const edited = await change.json();
  expect(`/booking/${edited.uid}`).not.toBe(path);
  await expect(page).toHaveURL(new RegExp(`/booking/${edited.uid}`));
  path = `/booking/${edited.uid}`;
  await page.screenshot({ path: ".scratch/qa/public-reschedule.png", fullPage: true });
  await page.goto(path);
  const cancel = page.getByRole("button", { name: /cancel/i }).or(page.getByRole("link", { name: /cancel/i }));
  await expect(cancel.first()).toBeVisible();
  await cancel.first().click();
  await expect(page.getByTestId("confirm_cancel").filter({ visible: true })).toBeVisible();
  await page.screenshot({ path: ".scratch/qa/public-cancel.png", fullPage: true });
  await page.getByTestId("cancel_reason").filter({ visible: true }).fill("Disposable booking check");
  const cancelled = page.waitForResponse(response => new URL(response.url()).pathname === "/api/cancel" && response.request().method() === "POST");
  await page.getByTestId("confirm_cancel").filter({ visible: true }).click();
  expect((await cancelled).ok()).toBe(true);
  await expect(page.getByTestId("confirm_cancel").filter({ visible: true })).toHaveCount(0);
});
