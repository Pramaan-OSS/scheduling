import { test, expect } from "@playwright/test";
test.beforeEach(async ({ context }) => { await context.route("**/*", route => ["localhost", "127.0.0.1"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort()); });
test("event search and booking pagination use the saved records", async ({ page }) => {
  await page.goto("/event-types");
  await page.getByPlaceholder("Search", { exact: true }).filter({ visible: true }).fill("QA public visit");
  await expect(page.getByTestId("event-types").filter({ visible: true })).toContainText("QA public visit");
  await expect(page.getByTestId("event-types").filter({ visible: true })).not.toContainText("QA checkout visit");
  await page.getByPlaceholder("Search", { exact: true }).filter({ visible: true }).fill("no-such-event-type-fixture");
  await expect(page.getByText("QA public visit", { exact: true })).toHaveCount(0);
  const listed = page.waitForResponse(response => new URL(response.url()).pathname.includes("bookings/get") && response.ok());
  await page.goto("/bookings/upcoming");
  const response = await (await listed).json();
  const times = response[0].result.data.json.bookings.map((row: { startTime: string }) => Date.parse(row.startTime));
  expect(times.length).toBeGreaterThan(1);
  expect(times).toEqual([...times].sort((a, b) => a - b));
  const next = page.getByRole("button", { name: "Next", exact: true });
  await expect(next).toBeEnabled();
  await next.click();
  await expect(page.locator("body")).toContainText(/11-\d+ of/);
  await page.getByRole("button", { name: "Previous", exact: true }).click();
  await expect(page.locator("body")).toContainText(/1-10 of/);
  const originalRange = await page.getByText(/^1-10 of \d+$/).innerText();
  await page.getByRole("button", { name: "Filter", exact: true }).click();
  await page.getByRole("option", { name: "Attendees Name", exact: true }).click();
  const filter = page.getByTestId("text-filter-options-attendeeName").filter({ visible: true });
  await filter.locator("input[name=operand]").fill("QA guest 6");
  await filter.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(page.locator("body")).toContainText("QA booking 6");
  await expect(page.locator("body")).not.toContainText("QA booking 7");
  await page.getByTestId("clear-filters-button").filter({ visible: true }).click();
  await expect(page.getByText(originalRange, { exact: true })).toBeVisible();
});
