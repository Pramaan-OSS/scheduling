import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
const fixture = JSON.parse(readFileSync(".scratch/qa/fixtures.json", "utf8"));
test.beforeEach(async ({ context }) => { await context.route("**/*", route => ["localhost", "127.0.0.1"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort()); });
test("a connected host approves a room preference and can return to pasted links", async ({ page }) => {
  await page.goto(`/event-types/${fixture.eventId}`);
  const enabled = page.getByLabel("Create a meeting room for this event type", { exact: true }).filter({ visible: true });
  await expect(enabled).toBeEnabled();
  await enabled.check();
  await page.getByLabel("Pasted fallback meeting link", { exact: true }).filter({ visible: true }).fill("https://meeting.example.test/fallback");
  await page.getByLabel("I approve creating and deleting one room per booking. Recording stays off. Private host links are shown only to the room owner.", { exact: true }).filter({ visible: true }).check();
  let saved = page.waitForResponse(response => new URL(response.url()).pathname === `/api/event-room/${fixture.eventId}` && response.request().method() === "POST");
  await page.getByRole("button", { name: "Save meeting preference", exact: true }).click(); expect((await saved).ok()).toBe(true);
  await page.reload(); await expect(enabled).toBeChecked();
  await enabled.uncheck();
  saved = page.waitForResponse(response => new URL(response.url()).pathname === `/api/event-room/${fixture.eventId}` && response.request().method() === "POST");
  await page.getByRole("button", { name: "Save meeting preference", exact: true }).click(); expect((await saved).ok()).toBe(true);
});
test("a host enables, shares, checks, changes and deletes a booking short link", async ({ page, context, baseURL }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/settings/my-account/calendars");
  const section = page.getByRole("heading", { name: "Your short-link app", exact: true }).locator("..");
  await expect(section.getByText("Connected with change access.", { exact: true })).toBeVisible();
  await section.getByRole("checkbox", { name: "I approve the account access described above.", exact: true }).check();
  const enabled = section.getByLabel("Use short links for booking links and text messages", { exact: true }).filter({ visible: true });
  if (!(await enabled.isChecked())) await enabled.click();
  await expect(enabled).toBeChecked();
  await page.goto("/event-types");
  await page.getByTestId("new-event-type").filter({ visible: true }).click();
  const title = `QA sharing ${Date.now()}`;
  await page.getByRole("dialog").getByLabel("Title", { exact: true }).filter({ visible: true }).fill(title);
  await page.getByRole("dialog").getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page).toHaveURL(/event-types\/\d+/);
  await page.goto("/event-types");
  await page.getByPlaceholder("Search", { exact: true }).filter({ visible: true }).fill(title);
  const created = page.waitForResponse(response => new URL(response.url()).pathname === "/api/short-links" && response.request().method() === "POST");
  await page.getByRole("button", { name: "Copy link to event", exact: true }).first().click();
  const creation = await created; expect(creation.ok()).toBe(true);
  expect((await creation.json()).shortLink).toMatch(/^https:\/\/short\.example\.test\//);
  const destination = creation.request().postDataJSON().destinationUrl;
  await page.goto("/settings/my-account/calendars");
  const manager = page.getByRole("heading", { name: "Your booking short links", exact: true }).locator("..");
  await manager.getByRole("button", { name: "Show saved links", exact: true }).click();
  const row = manager.locator("div.rounded").filter({ hasText: destination });
  async function act(name: string, action: string, target = row) {
    const response = page.waitForResponse(response => new URL(response.url()).pathname === "/api/short-links" && response.request().method() === "POST" && response.request().postDataJSON()?.action === action);
    await target.getByRole("button", { name, exact: true }).click();
    expect((await response).ok()).toBe(true);
  }
  await act("Check link", "get");
  await expect(row.getByRole("button", { name: "Check link", exact: true })).toBeEnabled();
  await act("Check recent clicks", "clicks");
  await expect(row.getByRole("button", { name: "Check recent clicks", exact: true })).toBeEnabled();
  const updatedDestination = `${baseURL}/${fixture.username}/qa-public`;
  await row.getByLabel("New booking destination", { exact: true }).filter({ visible: true }).fill(updatedDestination);
  await manager.getByRole("checkbox").check();
  await act("Change destination", "update");
  await expect(manager.getByRole("checkbox")).not.toBeChecked();
  const updated = manager.locator("div.rounded").filter({ has: page.locator(`input[value="${updatedDestination}"]`) });
  await manager.getByRole("checkbox").check();
  await act("Delete short link", "delete", updated);
  await expect(updated).toHaveCount(0);
});
